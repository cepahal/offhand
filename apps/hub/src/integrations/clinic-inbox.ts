import { appendFileSync, existsSync, mkdirSync, readFileSync } from "node:fs";
import { dirname, relative } from "node:path";
import { containsPhoneNumber, type AppId, type ShareEvent } from "@hoverscan/contracts";
import type { FastifyInstance } from "fastify";
import { REPO_ROOT } from "../config.js";
import type { Logger } from "../log/logger.js";
import type { Integration, IntegrationStatus, ShareContext } from "./integration.js";

/** One line of data/clinic-inbox.jsonl. The recipient is the opaque rcp_ ref, never a phone number. */
export interface InboxEntry {
  ts: string;
  shareId: string;
  app: AppId | null;
  caseId: string | null;
  recipientRef: string | null;
  optionId: string;
  optionLabel: string | null;
  selected: boolean;
}

/**
 * NeuroView's clinic-record stand-in: every vote becomes one JSON line in a local file, shown on
 * /debug. If the team picks ChairSide instead, the Open Dental integration replaces this.
 */
export class ClinicInboxIntegration implements Integration {
  readonly name = "clinicinbox";
  private lastError: string | undefined;

  constructor(
    readonly mode: "mock" | "live",
    readonly apps: readonly AppId[],
    readonly file: string,
    private readonly logger: Logger,
    private readonly now: () => number = Date.now,
  ) {}

  async start(): Promise<void> {
    mkdirSync(dirname(this.file), { recursive: true });
  }

  status(): IntegrationStatus {
    return this.lastError ? { up: false, reason: this.lastError } : { up: true };
  }

  onShareEvent(ev: ShareEvent, share: ShareContext | undefined): void {
    if (ev.kind !== "vote" || !ev.optionId) return;
    const entry: InboxEntry = {
      ts: new Date(this.now()).toISOString(),
      shareId: ev.shareId,
      app: share?.app ?? null,
      caseId: share?.caseId ?? null,
      recipientRef: share?.recipientRef ?? null,
      optionId: ev.optionId,
      optionLabel: share?.pollOptions.find((o) => o.id === ev.optionId)?.label ?? null,
      selected: ev.selected ?? true,
    };
    const line = JSON.stringify(entry);
    // Ids and the timestamp are generated by the hub; only the copied text fields could carry a number.
    if ([entry.optionId, entry.optionLabel ?? "", entry.caseId ?? ""].some(containsPhoneNumber)) {
      this.lastError = "refused to write an inbox line that looked like it held a phone number";
      this.logger.error({ integration: this.name, shareId: ev.shareId }, this.lastError);
      return;
    }
    try {
      appendFileSync(this.file, `${line}\n`, { mode: 0o600 });
      this.lastError = undefined;
      this.logger.info({ integration: this.name, shareId: ev.shareId, optionId: ev.optionId }, "vote written to the clinic inbox");
    } catch (err) {
      this.lastError = `could not write the clinic inbox: ${(err as Error).message}`;
      this.logger.error({ integration: this.name }, this.lastError);
    }
  }

  /** Most recent entries first. Malformed lines are skipped. */
  entries(limit = 200): InboxEntry[] {
    if (!existsSync(this.file)) return [];
    return readFileSync(this.file, "utf8")
      .split("\n")
      .filter(Boolean)
      .flatMap((l) => {
        try {
          return [JSON.parse(l) as InboxEntry];
        } catch {
          return [];
        }
      })
      .slice(-limit)
      .reverse();
  }

  registerRoutes(app: FastifyInstance): void {
    app.get("/api/integrations/clinicinbox/entries", async () => ({ file: relative(REPO_ROOT, this.file), entries: this.entries() }));
  }
}
