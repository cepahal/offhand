"""The test-pattern case pack: nested cubes, three marker spheres and RAS axis arrows.

Deliberately NOT anatomy. It exercises every viewer feature (peel order, transparency, findings,
fly-to, clip scrub, orientation) without any patient data, and it is the only case pack that is
committed to git.

Orientation check: the red sphere/arrow is +R (patient right), green is +A (anterior), blue is +S
(superior). In the viewer's default front view, red points to the viewer's LEFT, blue points up,
green points at the viewer.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import numpy as np
import trimesh

from . import casepack

TITLE = "Test pattern — NOT ANATOMY"

CUBES = [  # id, label, edge mm, colour, opacity, peelOrder
    ("cube-outer", "Outer cube (120 mm)", 120.0, "#3366cc", 0.2, 0),
    ("cube-middle", "Middle cube (80 mm)", 80.0, "#33aa66", 0.35, 1),
    ("cube-inner", "Inner cube (40 mm)", 40.0, "#cc8833", 1.0, 2),
]

SPHERES = [  # id, label, centre RAS mm, radius mm
    ("sphere-r", "Marker +R (right)", (30.0, 0.0, 0.0), 8.0),
    ("sphere-a", "Marker +A (anterior)", (0.0, 30.0, 0.0), 6.0),
    ("sphere-s", "Marker +S (superior)", (0.0, 0.0, 30.0), 10.0),
]

AXIS_COLORS = {"R": (220, 40, 40, 255), "A": (40, 180, 60, 255), "S": (50, 90, 230, 255)}


def _arrow(direction: np.ndarray, length: float, color: tuple[int, int, int, int]) -> trimesh.Trimesh:
    shaft_len = length * 0.82
    shaft = trimesh.creation.cylinder(radius=1.2, height=shaft_len, sections=16)
    shaft.apply_translation([0, 0, shaft_len / 2])
    head = trimesh.creation.cone(radius=3.5, height=length - shaft_len, sections=16)
    head.apply_translation([0, 0, shaft_len])
    arrow = trimesh.util.concatenate([shaft, head])
    rot = trimesh.geometry.align_vectors([0, 0, 1], direction)
    arrow.apply_transform(rot)
    arrow.visual.vertex_colors = np.tile(np.array(color, dtype=np.uint8), (len(arrow.vertices), 1))
    return arrow


def axes_mesh(length: float = 80.0) -> trimesh.Trimesh:
    parts = [
        _arrow(np.array(d, dtype=float), length, AXIS_COLORS[k])
        for k, d in (("R", (1, 0, 0)), ("A", (0, 1, 0)), ("S", (0, 0, 1)))
    ]
    origin = trimesh.creation.icosphere(subdivisions=2, radius=2.5)
    origin.visual.vertex_colors = np.tile(np.array([230, 230, 230, 255], dtype=np.uint8), (len(origin.vertices), 1))
    return trimesh.util.concatenate([*parts, origin])


def build_testpattern(out: Path) -> dict[str, Any]:
    out.mkdir(parents=True, exist_ok=True)
    layers = []
    for lid, label, edge, color, opacity, peel in CUBES:
        casepack.write_glb(trimesh.creation.box(extents=(edge, edge, edge)), out / "layers" / f"{lid}.glb")
        layers.append(casepack.layer_entry(lid, label, color, opacity, peel))

    spheres = []
    for _sid, _label, center, r in SPHERES:
        s = trimesh.creation.icosphere(subdivisions=3, radius=r)
        s.apply_translation(center)
        spheres.append(s)
    casepack.write_glb(trimesh.util.concatenate(spheres), out / "layers" / "markers.glb")
    layers.append(casepack.layer_entry("markers", "Marker spheres", "#ffdd33", 1.0, 3))

    casepack.write_glb(axes_mesh(), out / "layers" / "axes.glb")
    layers.append(casepack.layer_entry("axes", "RAS axes (R red, A green, S blue)", "#ffffff", 1.0, 3))

    findings = [
        {
            "id": sid,
            "label": label,
            "layerId": "markers",
            "center": list(center),
            "radiusMm": r,
            "provenance": "measured",
        }
        for sid, label, center, r in SPHERES
    ]

    app = out.parent.name
    manifest: dict[str, Any] = {
        "schema": 1,
        "app": app,
        "caseId": out.name,
        "title": TITLE,
        "source": {
            "dataset": "offhand test pattern (synthetic geometry, no patient data)",
            "url": "",
            "license": "Generated by offhand; no third-party data",
            "citation": "Generated by `offhand-pipeline testpattern`.",
            "subjectId": "none",
        },
        "deidentified": True,
        "coordinateSystem": "RAS",
        "units": "mm",
        "layers": layers,
        "volumes": [],
        "findings": findings,
        "share": {"templateId": "test-pattern", "pollOptions": []},
        "policyId": "none",
    }
    casepack.write_manifest(manifest, out)
    return manifest
